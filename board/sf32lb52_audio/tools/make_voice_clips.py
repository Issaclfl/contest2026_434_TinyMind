#!/usr/bin/env python3
"""把固定播报语合成为 16 kHz 单声道 16bit 裸 PCM，并生成 C 头文件（离线播报用）。

为什么离线要用预合成片段：TTS 在云上，断网就哑。智能家居的固定播报
（开灯/关灯/离线提示）完全可以预先合成好烧进固件，播放时零网络依赖。

用法（在 WSL 里跑，那里有网络和 python3）：
    python3 make_voice_clips.py <输出目录> <sdkconfig路径>

产物：
    <输出目录>/<name>.pcm        16 kHz mono s16le 裸 PCM
    <输出目录>/voice_clips.h     带 C 数组 + 名字表的头文件
"""

