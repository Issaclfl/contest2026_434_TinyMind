def load_key(path):
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = re.match(r'^CONFIG_GATEWAY_CLOUD_API_KEY="(.*)"', line.strip())
            if m and m.group(1):
                return m.group(1)
    raise SystemExit("找不到 API key: %s" % path)


def synth(text, key):
    body = json.dumps({
        "model": "mimo-v2.5-tts",
        "messages": [{"role": "assistant", "content": text}],
        "audio": {"format": "wav", "voice": VOICE},
    }).encode("utf-8")

    req = urllib.request.Request(HOST, data=body, headers={
        "Authorization": "Bearer %s" % key,
        "Content-Type": "application/json",
    })

    with urllib.request.urlopen(req, timeout=90) as resp:
        doc = json.loads(resp.read().decode("utf-8"))

    b64 = doc["choices"][0]["message"]["audio"]["data"]
    return base64.b64decode(b64)


def wav_to_pcm16k_mono(wav):
    """WAV(24k mono s16) -> 16k mono s16，与板端同一条 3:2 取平均的算法。"""
    pos = 12
    rate = channels = bits = None
    pcm = None

    while pos + 8 <= len(wav):
        cid = wav[pos:pos + 4]
        size = struct.unpack("<I", wav[pos + 4:pos + 8])[0]
        body = wav[pos + 8:pos + 8 + size]
        if cid == b"fmt ":
            channels, rate = struct.unpack("<HI", body[2:8])
            bits = struct.unpack("<H", body[14:16])[0]
        elif cid == b"data":
            pcm = body
            break
        pos += 8 + size + (size & 1)

    if pcm is None or rate != 24000 or channels != 1 or bits != 16:
        raise SystemExit("意外的 WAV 格式: rate=%s ch=%s bits=%s" % (rate, channels, bits))

    samples = struct.unpack("<%dh" % (len(pcm) // 2), pcm[: len(pcm) // 2 * 2])
    frames = len(samples)

    # 抗混叠低通（Blackman 窗 sinc，截止 7 kHz）之后再做 3:2 插值：
    # 直接丢采样会把 8 kHz 以上的分量折回可听带，听感发沙、发卡。
    import math

    cutoff = 7000.0 / rate
    taps_n = 63
    half = (taps_n - 1) / 2.0
    taps = []
    for i in range(taps_n):
        x = i - half
        if abs(x) < 1e-9:
            h = 2 * cutoff
        else:
            h = math.sin(2 * math.pi * cutoff * x) / (math.pi * x)
        w = (0.42 - 0.5 * math.cos(2 * math.pi * i / (taps_n - 1))
             + 0.08 * math.cos(4 * math.pi * i / (taps_n - 1)))
        taps.append(h * w)
    gain = sum(taps)
    taps = [t / gain for t in taps]

    filtered = [0.0] * frames
    for i in range(frames):
        acc = 0.0
        lo = i - int(half)
        for j, c in enumerate(taps):
            k = lo + j
            if 0 <= k < frames:
                acc += samples[k] * c
        filtered[i] = acc

    out_frames = (frames * 2) // 3
    out = []
    for k in range(out_frames):
        pos = k * 1.5
        i0 = int(pos)
        frac = pos - i0
        a = filtered[i0]
        b = filtered[i0 + 1] if i0 + 1 < frames else a
        v = a + (b - a) * frac
        if v > 32767:
            v = 32767
        elif v < -32768:
            v = -32768
        out.append(int(v))

    return struct.pack("<%dh" % len(out), *out)


def emit_header(clips, path):
    lines = [
        "/* Generated by make_voice_clips.py -- do not edit by hand.",
        " *",
        " * Offline announcement clips: 16 kHz mono 16-bit PCM, synthesized once",
        " * and embedded in the image so the device can speak with no network.",
        " */",
        "",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "",
        "typedef struct {",
        "    const char *name;",
        "    const unsigned char *pcm;",
        "    size_t len;",
        "} voice_clip_t;",
        "",
    ]

    for name, data in clips:
        lines.append("static const unsigned char clip_%s[] = {" % name)
        row = []
        for i, byte in enumerate(data):
            row.append("0x%02x," % byte)
            if len(row) == 16:
                lines.append("    " + "".join(row))
                row = []
        if row:
            lines.append("    " + "".join(row))
        lines.append("};")
        lines.append("")

    lines.append("static const voice_clip_t voice_clips[] = {")
    for name, data in clips:
        lines.append('    { "%s", clip_%s, sizeof(clip_%s) },' % (name, name, name))
    lines.append("};")
    lines.append("")
    lines.append("#define VOICE_CLIP_COUNT (sizeof(voice_clips) / sizeof(voice_clips[0]))")
    lines.append("")

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main():
    key = load_key(SDKCONFIG)
    os.makedirs(OUT_DIR, exist_ok=True)

    out = []
    total = 0

    for name, text in CLIPS:
        wav = synth(text, key)
        pcm = wav_to_pcm16k_mono(wav)
        with open(os.path.join(OUT_DIR, name + ".pcm"), "wb") as fh:
            fh.write(pcm)
        seconds = len(pcm) / (16000 * 2)
        print("%-10s %-16s %6d bytes  %.2f s" % (name, text, len(pcm), seconds))
        out.append((name, pcm))
        total += len(pcm)

    header = os.path.join(OUT_DIR, "voice_clips.h")
    emit_header(out, header)
    print("\n合计 %d 字节（%.0f KB），头文件 %s" % (total, total / 1024, header))


if __name__ == "__main__":
    main()
